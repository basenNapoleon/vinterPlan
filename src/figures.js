// Namn i appen som pekar på samma figur
const FIG_ALIAS = { 'Knäböj': 'Knäböj eller trap bar-marklyft' };

function figurSVG(namn, liten) {
  const f = FIG[namn] || FIG[FIG_ALIAS[namn]];
  if (!f) return '';
  const ps = f.poses.concat([f.poses[0]]);
  const vals = (key, i) => ps.map(p => (p[key] || p[key.replace('2', '1')])[i]).join(';');
  const dur = f.dur + 's';
  const an = (attr, key, i) => `<animate attributeName="${attr}" values="${vals(key, i)}" dur="${dur}" repeatCount="indefinite" calcMode="spline" keySplines="${ps.slice(1).map(() => '0.45 0 0.55 1').join(';')}"/>`;
  const line = (a, b, cls) => `<line class="${cls}" x1="${f.poses[0][a][0]}" y1="${f.poses[0][a][1]}" x2="${f.poses[0][b][0]}" y2="${f.poses[0][b][1]}">${an('x1', a, 0)}${an('y1', a, 1)}${an('x2', b, 0)}${an('y2', b, 1)}</line>`;
  let s = `<svg viewBox="0 -10 200 146" class="fig${liten ? ' liten' : ''}" role="img" aria-label="${namn}">`;
  s += `<line class="golv" x1="4" y1="126" x2="196" y2="126"/>`;
  f.props.forEach(p => { s += `<rect class="prop" x="${p[1]}" y="${p[2]}" width="${p[3]}" height="${p[4]}" rx="3"/>`; });
  // bortre ben och arm först, ljusare
  s += line('p', 'k2', 'bak') + line('k2', 'f2', 'bak') + line('n', 'e2', 'bak') + line('e2', 'w2', 'bak');
  s += line('n', 'p', 'kropp') + line('p', 'k1', 'kropp') + line('k1', 'f1', 'kropp') + line('n', 'e1', 'kropp') + line('e1', 'w1', 'kropp');
  s += `<circle class="huvud" r="9" cx="${f.poses[0].h[0]}" cy="${f.poses[0].h[1]}">${an('cx', 'h', 0)}${an('cy', 'h', 1)}</circle>`;
  if (f.poses[0].b) {
    s += `<circle class="stang" r="7" cx="${f.poses[0].b[0]}" cy="${f.poses[0].b[1]}">${an('cx', 'b', 0)}${an('cy', 'b', 1)}</circle>`;
  }
  return s + '</svg>';
}
